DROP TABLE IF EXISTS consent_records;
DROP TABLE IF EXISTS shared_reports;
DROP TABLE IF EXISTS analysis_items;
DROP TABLE IF EXISTS analyses;
DROP TABLE IF EXISTS job_descriptions;
DROP TABLE IF EXISTS skill_aliases;
DROP TABLE IF EXISTS skills;
DROP TABLE IF EXISTS resume_versions;
DROP TABLE IF EXISTS resumes;
DROP TABLE IF EXISTS refresh_tokens;
DROP TABLE IF EXISTS guest_sessions;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id UUID PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(100),
    google_sub VARCHAR(255) UNIQUE,
    role VARCHAR(32) NOT NULL DEFAULT 'user',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (password_hash IS NOT NULL OR google_sub IS NOT NULL)
);

CREATE TABLE refresh_tokens (
    id UUID DEFAULT RANDOM_UUID() PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE guest_sessions (
    id UUID PRIMARY KEY,
    ip_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE resumes (
    id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE CASCADE,
    guest_session_id UUID REFERENCES guest_sessions(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE resume_versions (
    id UUID PRIMARY KEY,
    resume_id UUID NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL,
    s3_key VARCHAR(1024) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    mime VARCHAR(255) NOT NULL,
    size_bytes INTEGER NOT NULL,
    extracted_text CLOB,
    sections JSON,
    parse_warnings JSON DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (resume_id, version_no),
    UNIQUE (resume_id, sha256)
);

CREATE TABLE skills (
    id INTEGER PRIMARY KEY,
    canonical_name VARCHAR(255) NOT NULL UNIQUE,
    category VARCHAR(100) NOT NULL
);

CREATE TABLE skill_aliases (
    alias VARCHAR(255) PRIMARY KEY,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE
);

