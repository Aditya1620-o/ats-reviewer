CREATE TABLE job_descriptions (
    id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE CASCADE,
    guest_session_id UUID REFERENCES guest_sessions(id) ON DELETE CASCADE,
    is_template BOOLEAN NOT NULL DEFAULT FALSE,
    title VARCHAR(255) NOT NULL,
    raw_text VARCHAR(10000) NOT NULL,
    required_skill_ids INTEGER ARRAY NOT NULL DEFAULT ARRAY[],
    preferred_skill_ids INTEGER ARRAY NOT NULL DEFAULT ARRAY[],
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK ((user_id IS NULL) <> (guest_session_id IS NULL))
);

CREATE TABLE analyses (
    id UUID PRIMARY KEY,
    resume_version_id UUID NOT NULL REFERENCES resume_versions(id) ON DELETE CASCADE,
    jd_id UUID NOT NULL REFERENCES job_descriptions(id) ON DELETE CASCADE,
    engine_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'processing', 'done', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0,
    score DECIMAL(5, 2) CHECK (score BETWEEN 0 AND 100),
    error_code VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (resume_version_id, jd_id, engine_version)
);

CREATE TABLE analysis_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id UUID NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(id),
    weight DECIMAL(3, 1) NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('used', 'claimed', 'missing')),
    found_in VARCHAR(255),
    points DECIMAL(4, 2) NOT NULL,
    UNIQUE (analysis_id, skill_id)
);

CREATE TABLE shared_reports (
    token VARCHAR(22) PRIMARY KEY,
    analysis_id UUID NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE consent_records (
    id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    guest_session_id UUID REFERENCES guest_sessions(id) ON DELETE SET NULL,
    subject_hash VARCHAR(64) NOT NULL,
    notice_version VARCHAR(255) NOT NULL,
    age_confirmed_18 BOOLEAN NOT NULL,
    given_at TIMESTAMP WITH TIME ZONE NOT NULL,
    withdrawn_at TIMESTAMP WITH TIME ZONE
);